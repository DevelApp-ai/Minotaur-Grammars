#!/usr/bin/env python3
"""Generate the synthetic size-class grammars under benchmarks/synthetic/
(Minotaur-Grammars #192, feeds Minotaur#126/#131 compile-time benchmarks).

Deterministic: same output on every run. Classes (rule counts):
  rules-020  (~15-25)   rules-060  (50-80)   rules-180  (150-200)   rules-320  (300+)

Usage: python3 gen_synthetic.py [repo-root]
"""
import os, sys, json

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "benchmarks", "synthetic")

CLASSES = {"rules-020": 20, "rules-060": 60, "rules-180": 180, "rules-320": 320}

LICENSE = open(os.path.join(ROOT, "networking/apache-httpd-config/LICENSE"), encoding="utf-8").read()

def meta(name, n):
    return {
        "Id": "develapp.synthetic" + name[-3:], "Name": name, "Vendor": "DevelApp",
        "DisplayName": name, "Version": "2.0.0", "MinotaurVersion": "*",
        "Description": "Synthetic %d-rule grammar (generated by benchmarks/synthetic/gen_synthetic.py) for compile-time size-class benchmarks (Minotaur-Grammars #192, Minotaur #126/#131)." % n,
        "License": "MIT", "Tags": ["benchmark", "synthetic"], "MainFile": name + ".grammar",
        "Dependencies": [],
        "Documentation": "https://github.com/DevelApp-ai/Minotaur-Grammars",
        "Repository": "https://github.com/DevelApp-ai/Minotaur-Grammars",
        "Author": {"Username": "larsbuch", "FirstName": "Lars", "LastName": "Buch-Jepsen"},
        "PricingModel": "free",
    }

for name, n in CLASSES.items():
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)
    gf = name + ".grammar"
    lines = ["Grammar: %s" % name, "FormatType: EBNF", "",
             "/* Synthetic %d-rule grammar, generated by gen_synthetic.py (#192). */" % n, "",
             "<start> ::= <word>* ;",
             "<word> ::= " + " | ".join("<r%d>" % i for i in range(n)) + " | <ident> ;"]
    for i in range(n):
        lines.append("<r%d> ::= /kw%d/ ;" % (i, i))
    lines += ["<ident> ::= /[a-z][a-z0-9]*/ ;",
              "<ws> ::= /[ \\t\\r\\n]+/ => { skip } ;",
              ""]
    open(os.path.join(d, gf), "w", encoding="utf-8").write("\n".join(lines))
    cases = "lex: " + " ".join("kw%d" % i for i in range(0, n, max(1, n // 8))) + "\n"
    cases += "lex: hello kw1 world\n\n# Inputs that must be rejected by the token rules (LX1001).\nfail: \\u20ac\n"
    cases = ("# Conformance cases for %s - synthetic benchmark grammar (#192).\n" % gf
             + "# Run by the ENFAStepLexer-StepParser integration suite in GreedyLongestMatch mode.\n"
             + "grammar: %s\n\n" % gf + cases)
    open(os.path.join(d, "Conformance.txt"), "w", encoding="utf-8").write(cases)
    open(os.path.join(d, "Examples.txt"), "w", encoding="utf-8").write(
        "# Synthetic example for %s (#192).\n" % gf + " ".join("kw%d" % i for i in range(0, n, max(1, n // 4))) + " some words here\n")
    open(os.path.join(d, "minotaur-metadata.json"), "w", encoding="utf-8").write(json.dumps(meta(name, n), indent=2) + "\n")
    open(os.path.join(d, "LICENSE"), "w", encoding="utf-8").write(LICENSE)
    open(os.path.join(d, "README.md"), "w", encoding="utf-8").write(
        "# %s\n\nSynthetic %d-rule grammar generated by `benchmarks/synthetic/gen_synthetic.py` for compile-time size-class benchmarks (#192).\n" % (name, n))
    print("generated", d)
